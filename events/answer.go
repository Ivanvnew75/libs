// Package events — схема событий, которые ходят через Kafka.
//
// Пакет вынесен отдельно и не зависит ни от Kafka-библиотеки, ни от
// хранилищ. Причина: это КОНТРАКТ между сервисами. Если структура события
// лежит внутри продюсера, каждый потребитель описывает её у себя заново,
// и рассинхронизация — вопрос времени. Один тип в одном месте делает
// несовместимое изменение видимым на компиляции, а не в проде.
//
// В большом проекте это место занимает Schema Registry с Avro/Protobuf.
// Здесь — общий Go-пакет: он работает ровно до тех пор, пока все
// потребители пишутся на Go. Как только появится потребитель на Python —
// понадобится Registry, и это честная граница применимости такого решения.
//
// ПОЧЕМУ ПАКЕТ ЖИВЁТ В libs, А НЕ В РЕПОЗИТОРИИ ПОТРЕБИТЕЛЕЙ.
// Продюсер (telegram-api) и потребители (answers, analytics) лежат
// в РАЗНЫХ репозиториях. Положить контракт в moodbot-next/internal/
// нельзя технически: пакеты под internal/ невидимы за пределами модуля —
// это не соглашение, а правило компилятора. Значит, общий контракт
// обязан жить в общем модуле, и libs для этого и заводился.
// Практическое следствие: несовместимая правка события — это новая
// версия libs, и она видна в go.mod каждого сервиса. Именно то,
// что хочется от контракта.
package events

import (
	"encoding/json"
	"errors"
	"fmt"
	"time"
)

// TopicAnswers — имя топика с версией в самом имени.
//
// Версия в имени топика, а не только в поле схемы: несовместимое
// изменение формата = новый топик и параллельная работа двух версий,
// пока потребители переезжают. Переименовать топик «на месте» нельзя,
// а вот завести answers.v2 и постепенно переключить — можно.
const TopicAnswers = "answers.v1"

// TopicAnswersDLQ — куда уезжают сообщения, которые не удалось разобрать.
const TopicAnswersDLQ = "answers.v1.dlq"

// SchemaVersion — версия формата AnswerReceived.
//
// Совместимые изменения (добавили необязательное поле) версию не меняют:
// старый потребитель просто не увидит новое поле. Несовместимые
// (убрали поле, поменяли смысл) требуют новой версии И нового топика.
const SchemaVersion = 1

// AnswerReceived — пользователь ответил на вопрос бота.
//
// Имя в прошедшем времени — не стилистика. Событие описывает УЖЕ
// СЛУЧИВШИЙСЯ факт, его нельзя отклонить или «не выполнить».
// Команда (SaveAnswer) — просьба, у неё есть адресат и она может быть
// отвергнута. Разница определяет, кто за что отвечает: продюсер события
// не знает и не хочет знать, что с ним сделают потребители.
type AnswerReceived struct {
	// EventID — ключ идемпотентности. Детерминированный: tg-<update_id>.
	//
	// Kafka даёт at-least-once: при ребалансе consumer group или падении
	// потребителя между обработкой и коммитом offset сообщение придёт
	// повторно. Это не аварийный режим, а нормальная работа. Потребитель
	// обязан быть идемпотентным, и EventID — то, по чему он отличает
	// повтор от нового события.
	EventID string `json:"event_id"`

	Schema     int       `json:"schema"`
	OccurredAt time.Time `json:"occurred_at"`

	UserID     int64 `json:"user_id"`
	TelegramID int64 `json:"telegram_id"`

	Question string `json:"question"`
	Answer   string `json:"answer"`

	// RequestID — сквозной идентификатор из logs-цепочки telegram-api.
	// Позволяет найти одним грепом весь путь: сообщение в Telegram →
	// событие в Kafka → строка в Postgres → строка в ClickHouse.
	RequestID string `json:"request_id"`
}

// Key — ключ партиционирования.
//
// Ключ = user_id, потому что Kafka гарантирует порядок только внутри
// партиции. Все события одного пользователя обязаны идти в одну
// партицию, иначе два ответа подряд могут обработаться в обратном
// порядке, и «динамика настроения» станет фикцией.
func (a AnswerReceived) Key() []byte {
	return []byte(fmt.Sprintf("%d", a.UserID))
}

var (
	ErrBadSchema  = errors.New("unsupported schema version")
	ErrIncomplete = errors.New("event is missing required fields")
)

// Validate проверяет событие ПОСЛЕ разбора JSON.
//
// encoding/json молча оставляет нули в полях, которых нет во входных
// данных. Без явной проверки событие с пустым user_id доедет до базы
// и создаст запись, привязанную к несуществующему пользователю 0.
// Ошибка вылезет через неделю в отчёте, а не сейчас в логе.
func (a AnswerReceived) Validate() error {
	if a.Schema != SchemaVersion {
		return fmt.Errorf("%w: got %d, want %d", ErrBadSchema, a.Schema, SchemaVersion)
	}
	if a.EventID == "" || a.UserID == 0 || a.Answer == "" {
		return ErrIncomplete
	}
	return nil
}

func (a AnswerReceived) Marshal() ([]byte, error) { return json.Marshal(a) }

// ParseAnswerReceived разбирает и сразу валидирует событие.
//
// Обе ошибки — разбор и валидация — считаются НЕИСПРАВИМЫМИ:
// повторная попытка обработать тот же байтовый мусор даст тот же
// результат. Поэтому вызывающий код отправляет такое сообщение в DLQ
// и двигает offset дальше, а не ретраит бесконечно (см. kafkax).
func ParseAnswerReceived(b []byte) (AnswerReceived, error) {
	var a AnswerReceived
	if err := json.Unmarshal(b, &a); err != nil {
		return a, fmt.Errorf("unmarshal: %w", err)
	}
	return a, a.Validate()
}
